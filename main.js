// ===== INTERSECTION OBSERVER =====
const revealEls = document.querySelectorAll(
  '.step-card,.feat-card,.app-feature,.quote-card,' +
  '#hero-badge,#hero-headline,#hero-sub,#hero-actions,#hero-stats,#hero-visuals,' +
  '.app-text,.family-text,.family-image-wrap'
);
revealEls.forEach(el => el.classList.add('reveal'));

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      if (entry.target.classList.contains('step-card')) entry.target.classList.add('animate');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });
revealEls.forEach(el => observer.observe(el));

// ===== HERO STAGGER =====
['hero-badge','hero-headline','hero-sub','hero-actions','hero-stats'].forEach((id, i) => {
  const el = document.getElementById(id);
  if (!el) return;
  el.style.cssText = 'opacity:0;transform:translateY(24px)';
  setTimeout(() => {
    el.style.transition = 'opacity .7s ease, transform .7s ease';
    el.style.opacity = '1';
    el.style.transform = 'translateY(0)';
  }, 200 + i * 150);
});
const hv = document.getElementById('hero-visuals');
if (hv) {
  hv.style.cssText = 'opacity:0;transform:translateX(30px)';
  setTimeout(() => { hv.style.transition = 'opacity 1s ease, transform 1s ease'; hv.style.opacity='1'; hv.style.transform='translateX(0)'; }, 600);
}

// ===== WAITLIST =====
function handleWaitlist() {
  const input = document.getElementById('email-input');
  const success = document.getElementById('cta-success');
  const btn = document.getElementById('btn-waitlist');
  const email = input.value.trim();
  if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    input.style.borderColor = 'rgba(239,68,68,0.6)';
    setTimeout(() => { input.style.borderColor = ''; }, 2000);
    return;
  }
  btn.style.opacity = '0.6';
  btn.style.pointerEvents = 'none';
  setTimeout(() => {
    input.parentElement.style.display = 'none';
    success.classList.remove('hidden');
  }, 900);
}

// ===== MOUSE PARALLAX =====
window.addEventListener('mousemove', (e) => {
  const x = (e.clientX / window.innerWidth - 0.5) * 20;
  const y = (e.clientY / window.innerHeight - 0.5) * 20;
  document.querySelectorAll('.floating-chip').forEach((chip, i) => {
    const f = (i + 1) * 0.4;
    chip.style.transform = `translate(${x*f}px,${y*f}px)`;
  });
  const di = document.getElementById('device-img');
  if (di) di.style.transform = `translateY(0) rotateY(${x*0.3}deg) rotateX(${-y*0.2}deg)`;
});

